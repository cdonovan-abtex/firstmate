import assert from 'node:assert/strict';
import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const root=process.cwd();
const scratch=resolve(root,'.qualification-test-scratch');
const evidence='/Users/abtex-mini/.no-mistakes/evidence/01M496VHA0F1NRTKZZJ1K1FWV6';
const fixture=resolve(scratch,'dependency-verdict');
const home=resolve(fixture,'home');
mkdirSync(resolve(fixture,'bin'),{recursive:true});
mkdirSync(resolve(home,'state'),{recursive:true});
mkdirSync(resolve(home,'config'),{recursive:true});
const {monitoringStopVerdict,monitoringStopped}=await import(pathToFileURL(resolve(root,'.pi/extensions/lib/fm-monitoring-stop.ts')));
const paths={root:fixture,home,state:resolve(home,'state'),config:resolve(home,'config')};
const results=[];
function observe(label,expected,stopped){
  const verdict=monitoringStopVerdict(paths);
  assert.equal(verdict.status,expected);
  assert.equal(monitoringStopped(paths),stopped);
  results.push({case:label,verdict,automaticMonitoringBlocked:stopped});
}
observe('Imported TS module without its executable companion','malformed',true);
copyFileSync(resolve(root,'bin/fm-monitoring-stop.sh'),resolve(fixture,'bin/fm-monitoring-stop.sh'));
observe('Executable companion without its sourced parser','malformed',true);
copyFileSync(resolve(root,'bin/fm-monitoring-stop-lib.sh'),resolve(fixture,'bin/fm-monitoring-stop-lib.sh'));
observe('All three real dependencies; isolated home has no receipt','none',false);
const receipt=resolve(home,'data/automatic-monitoring-pause/receipt.json');
mkdirSync(resolve(home,'data/automatic-monitoring-pause'),{recursive:true});
writeFileSync(receipt,'{}\n');
observe('All real dependencies; malformed isolated stop receipt','malformed',true);
writeFileSync(receipt,JSON.stringify({instruction:'Stop automatic monitoring.',time:'2026-10-06T18:00:00Z',home,scope:'automatic monitoring',resume:'Only on explicit request',action:'Stopped',completed:true})+'\n');
observe('All real dependencies; valid completed isolated stop receipt','active',true);
writeFileSync(resolve(evidence,'dependency-verdicts.json'),JSON.stringify(results,null,2)+'\n');
console.log(JSON.stringify(results,null,2));

// Reopen the actual SDK-generated output captured from the unmodified tracked test.
const captured=JSON.parse(readFileSync(resolve(evidence,'tracked-fix-fixture-runtime.json'),'utf8')).files_observed_before_fixture_cleanup;
const [sessionPath,sessionText]=Object.entries(captured).find(([key])=>key.startsWith('delivery-sessions/'));
const sessions=resolve(scratch,'replay-sessions');
const agentDir=resolve(scratch,'replay-agent-dir');
const replayCwd=resolve(scratch,'replay-cwd');
for(const dir of [sessions,agentDir,replayCwd]) mkdirSync(dir,{recursive:true});
const sessionFile=resolve(sessions,sessionPath.split('/').at(-1));
writeFileSync(sessionFile,sessionText);
const pkg='/Users/abtex-mini/.local/lib/node_modules/@earendil-works/pi-coding-agent';
const {DefaultResourceLoader,InteractiveMode,SessionManager,SettingsManager,createAgentSession,initTheme}=await import(pathToFileURL(resolve(pkg,'dist/index.js')));
initTheme('dark');
const manager=SessionManager.open(sessionFile,sessions);
const settings=SettingsManager.create(replayCwd,agentDir);
const loader=new DefaultResourceLoader({cwd:replayCwd,agentDir,settingsManager:settings,additionalExtensionPaths:[resolve(root,'.pi/extensions/fm-branch-supervision.ts')],noSkills:true,noPromptTemplates:true,noThemes:true,noContextFiles:true});
await loader.reload();
assert.deepEqual(loader.getExtensions().errors,[]);
const created=await createAgentSession({cwd:replayCwd,sessionManager:manager,settingsManager:settings,resourceLoader:loader,tools:[]});
const interactive=new InteractiveMode({session:created.session,setBeforeSessionInvalidate(){},setRebindSession(){}},{tuiMode:'alt-screen'});
interactive.renderCurrentSessionState();
const rendered=interactive.chatContainer.render(240).join('\n');
const summary='Completed diagnosis proves the prior assistant response was unrelated.';
writeFileSync(resolve(evidence,'real-sdk-reopened-transcript.ansi'),rendered+'\n');
assert.ok(rendered.includes(summary));
assert.ok(rendered.includes('[seq 234]'));
assert.equal(rendered.split(summary).length,2);
assert.ok(!manager.buildSessionContext().messages.some(message=>JSON.stringify(message).includes(summary)));
writeFileSync(resolve(evidence,'real-sdk-reopened-transcript.ansi'),rendered+'\n');
console.log('REOPENED SDK TRANSCRIPT:\n'+rendered);
await created.session.dispose();
process.exit(0);
